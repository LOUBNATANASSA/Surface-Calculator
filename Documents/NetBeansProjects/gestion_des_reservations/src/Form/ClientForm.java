    private void Ajouter_ClientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Ajouter_ClientActionPerformed
    String nom = NomBox.getText();
    String prenom = PrenomBox.getText();
    String telephone = TelephoneBox.getText();
    String email = EmailBox.getText();
    String cin = CIN_Box.getText();

    if (nom.isEmpty() || prenom.isEmpty() || telephone.isEmpty() || email.isEmpty() || cin.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Tous les champs sont obligatoires.", "Erreur", JOptionPane.ERROR_MESSAGE);
    } else {
        Client client = new Client(nom, prenom, telephone, email, cin);
        c.create(client);
        JOptionPane.showMessageDialog(this, "Client ajouté avec succès.");
        load();
    }
    }//GEN-LAST:event_Ajouter_ClientActionPerformed

    private void Supprimer_ClientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Supprimer_ClientActionPerformed
      if(NomBox.getText().isEmpty() ){JOptionPane.showMessageDialog(this, "veillez choisir un client depuit la liste", "Erreur", JOptionPane.ERROR_MESSAGE);}
      else{
        int reponse=JOptionPane.showConfirmDialog(this, "voulez vous vraiment supprimer ce client");
        if(reponse==0){
            if(c.delete(c.findById(id))){
                JOptionPane.showMessageDialog(this,"le client a été bien supprimé");
                load();
            }
        }}
    }//GEN-LAST:event_Supprimer_ClientActionPerformed

