    private void Modifier_ClientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Modifier_ClientActionPerformed
              if(NomBox.getText().isEmpty() ){JOptionPane.showMessageDialog(this, "veillez choisir un client depuit la liste");}
              else{
        String nom=NomBox.getText();
        String prenom=PrenomBox.getText();
        String tel=TelephoneBox.getText();
        String mail=EmailBox.getText();
        String cin=CIN_Box.getText();
        Client cl=c.findById(id);
        cl.setNom(nom);
        cl.setPrenom(prenom);
        cl.setTelephone(tel);
        cl.setEmail(mail);
        cl.setCIN(cin);
        int reponse=JOptionPane.showConfirmDialog(this, "Voulez vous vraiment modifier ce client");
        if(reponse==0){
            if(c.update(cl)){
                JOptionPane.showMessageDialog(this, "Client bien modifié");
                load();
            }
            else{JOptionPane.showMessageDialog(this, "erreur de modification");}
        }
      
        
              }
    }//GEN-LAST:event_Modifier_ClientActionPerformed

