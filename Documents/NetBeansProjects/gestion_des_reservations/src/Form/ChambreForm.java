    private void chambrelisteMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_chambrelisteMousePressed
          
        int row = chambreliste.getSelectedRow();  // Récupérer la ligne sélectionnée dans la table
    if (row != -1) {
        // Récupérer les données de la ligne sélectionnée
        id = (int) chambreliste.getValueAt(row, 0);  // Id de la chambre
        String numero = (String) chambreliste.getValueAt(row, 2);  // Numéro de la chambre
        String telephone = (String) chambreliste.getValueAt(row, 1);  // Téléphone
        String categorieCode = (String) chambreliste.getValueAt(row, 3);  // Code de la catégorie

        // Remplir les champs de texte
        Numero_Box.setText(numero);
        Telephone_Box.setText(telephone);
        
        // Sélectionner la catégorie dans le JComboBox
        for (int i = 0; i < a.size(); i++) {
            Categorie categorie = a.get(i);
            if (categorie.getCode().equals(categorieCode)) {
                Chambre_Categorie_Box.setSelectedItem(categorie.getCode());
                break;
            }
        }
    }
     
    }//GEN-LAST:event_chambrelisteMousePressed

    
    
    
    
    
    private void Modifier_ChambreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Modifier_ChambreActionPerformed
            // Vérification des champs obligatoires
    if (Numero_Box.getText().isEmpty() || Telephone_Box.getText().isEmpty() || Chambre_Categorie_Box.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs, y compris la catégorie.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return; // Arrêter l'exécution si des champs sont vides
    }

    // Récupérer les informations du formulaire
    String numero = Numero_Box.getText();
    String telephone = Telephone_Box.getText();
    String codeCategorie = (String) Chambre_Categorie_Box.getSelectedItem(); // Récupérer le code de la catégorie

    // Trouver l'objet Categorie correspondant au code sélectionné
    Categorie o = null;
    for (int i = 0; i < a.size(); i++) {
        Categorie ce = a.get(i);
        if (ce.getCode().equals(codeCategorie)) {
            o = ce; // Trouver la catégorie
            break;
        }
    }

    // Vérifier si la catégorie a été trouvée
    if (o == null) {
        JOptionPane.showMessageDialog(this, "Catégorie non trouvée.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return; // Si la catégorie n'est pas trouvée, arrêter l'exécution
    }

    // Trouver la chambre à modifier
    System.out.println("ID de la chambre à modifier : " + id); 
    Chambre c = Chs.findById(id);
    if (c == null) {
        JOptionPane.showMessageDialog(this, "Chambre non trouvée.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Mettre à jour les informations de la chambre
    c.setnumero(numero);
    c.setTelephone(telephone);
    c.setCategorie(o); // Assigner la nouvelle catégorie

    // Demander confirmation de la modification
    int reponse = JOptionPane.showConfirmDialog(this, "Voulez-vous vraiment modifier cette chambre?");
    if (reponse == 0) { // Si l'utilisateur confirme
        if (Chs.update(c)) { // Mettre à jour la chambre dans la base de données
            JOptionPane.showMessageDialog(this, "Chambre bien modifiée");
            load(); // Recharger les données ou actualiser l'affichage
        } else {
            JOptionPane.showMessageDialog(this, "Erreur de modification de la chambre", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_Modifier_ChambreActionPerformed

    
    

