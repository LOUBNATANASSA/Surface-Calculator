   private void remplirChambreCategorieBox() {
       
    try {
        List<Categorie> categories = categorie.findAll(); // Utilisation de la variable membre existante
        Chambre_Categorie_Box.removeAllItems();
        for (Categorie categorie : categories) {
            Chambre_Categorie_Box.addItem(categorie.getCode());
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erreur lors du remplissage des catégories : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
    }
}


